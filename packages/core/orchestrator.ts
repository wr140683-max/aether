/**
 * Helix Orchestrator
 * Planner → Coder → Tester with human checkpoints and retry limits.
 * Uses the LLM + Sandbox abstractions. No silent loops.
 */

import type { Plan, Task, Diff, TestEvidence, AgentMessage, ProjectContext } from "./types";
import { generate, type LLMConfig, estimateCost } from "./llm";
import { createPlannerPrompt } from "../agents/planner";

export interface OrchestratorConfig {
  maxRetriesPerTask: number;
  requireHumanApproval: boolean;
  llm: LLMConfig;
}

export class HelixOrchestrator {
  private history: AgentMessage[] = [];
  private config: OrchestratorConfig;
  private sessionCost = 0;

  constructor(config: OrchestratorConfig) {
    this.config = {
      maxRetriesPerTask: 3,
      requireHumanApproval: true,
      ...config,
    };
  }

  getSessionCost() {
    return this.sessionCost;
  }

  getHistory() {
    return this.history;
  }

  private add(msg: AgentMessage) {
    this.history.push(msg);
  }

  async plan(userGoal: string, existingFiles: string[] = []): Promise<Plan> {
    const prompt = createPlannerPrompt({ userGoal, existingFiles });
    const result = await generate(this.config.llm, "You are the Planner agent in Helix.", prompt);

    if (result.usage) {
      this.sessionCost += estimateCost(
        this.config.llm.provider,
        result.usage.promptTokens,
        result.usage.completionTokens
      );
    }

    this.add({
      role: "planner",
      content: result.text,
      timestamp: new Date().toISOString(),
    });

    const plan: Plan = {
      id: `plan-${Date.now()}`,
      summary: `Plan for: ${userGoal.slice(0, 80)}`,
      architectureNotes: "Generated by Helix Planner (stub until real model wired)",
      tasks: [
        {
          id: "task-1",
          title: "Implement core feature",
          description: userGoal,
          status: "pending",
        },
      ],
      stackChoices: {
        frontend: "Next.js",
        backend: "Next.js API routes",
        database: "SQLite",
      },
      createdAt: new Date().toISOString(),
    };

    return plan;
  }

  async runGoal(userGoal: string, ctx: ProjectContext) {
    throw new Error(
      "Use plan() + explicit code/test steps with human approval. Full auto runGoal is disabled by design to prevent Emergent-style silent loops."
    );
  }
}
